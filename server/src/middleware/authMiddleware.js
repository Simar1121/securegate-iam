import jwt from 'jsonwebtoken';
import crypto from 'crypto';
import User from '../models/User.js';
import RevokedToken from '../models/RevokedToken.js';
import Device from '../models/Device.js';

// Protect routes: verify JWT, ensure token is not revoked, verify session version and active user status
export const protect = async (req, res, next) => {
  let token;

  const authHeader = req.headers.authorization;
  if (authHeader && authHeader.startsWith('Bearer ')) {
    token = authHeader.split(' ')[1];
  }

  if (!token) {
    return res.status(401).json({
      success: false,
      message: 'Access denied: No authorization token provided.',
    });
  }

  const secret = process.env.JWT_SECRET;
  if (!secret || secret.trim().length < 32) {
    console.error('[SECURITY CRITICAL] Server JWT_SECRET is missing or has insufficient entropy (< 32 characters).');
    return res.status(500).json({
      success: false,
      message: 'Server security configuration error. Contact administrator.',
    });
  }

  try {
    // 1. Verify token signature and expiration
    const decoded = jwt.verify(token, secret);

    // Require the claims generated by SecureGate; reject legacy or malformed tokens.
    if (!decoded.id || !Number.isInteger(decoded.tokenVersion) || !Number.isInteger(decoded.exp) ||
        decoded.mfaVerified !== true || typeof decoded.deviceIdHash !== 'string' ||
        !/^[a-f0-9]{64}$/i.test(decoded.deviceIdHash)) {
      return res.status(401).json({
        success: false,
        message: 'This session was not issued after mandatory MFA and device verification. Please sign in again.',
      });
    }

    // Require the current browser instance to present the same random device
    // identifier used when this MFA session was issued.
    const presentedDeviceId = req.get('X-SecureGate-Device');
    if (typeof presentedDeviceId !== 'string' || !/^[a-f0-9]{64}$/i.test(presentedDeviceId)) {
      return res.status(401).json({
        success: false,
        message: 'This request is missing the registered device binding. Sign in again from your registered browser.',
      });
    }
    const presentedDeviceHash = crypto.createHmac('sha256', secret).update(presentedDeviceId).digest('hex');
    const expectedDeviceHash = Buffer.from(decoded.deviceIdHash, 'hex');
    const suppliedDeviceHash = Buffer.from(presentedDeviceHash, 'hex');
    if (!crypto.timingSafeEqual(expectedDeviceHash, suppliedDeviceHash)) {
      return res.status(401).json({
        success: false,
        message: 'This session is bound to a different device. Sign in again from your registered browser.',
      });
    }

    // 2. Store/check only a SHA-256 digest of revoked JWTs, never the bearer token itself.
    const tokenHash = crypto.createHash('sha256').update(token).digest('hex');
    const isRevoked = await RevokedToken.findOne({
      $or: [{ tokenHash }, { token }], // `token` supports revocations created by earlier SecureGate builds.
    });
    if (isRevoked) {
      return res.status(401).json({
        success: false,
        message: 'Session has been revoked or signed out. Please login again.',
      });
    }

    // 3. Fetch user and populate role along with permissions
    const user = await User.findById(decoded.id).populate({
      path: 'role',
      populate: {
        path: 'permissions',
        model: 'Permission',
      },
    });

    if (!user) {
      return res.status(401).json({
        success: false,
        message: 'Authentication failed: User account no longer exists.',
      });
    }

    // 4. Verify token version against user's current tokenVersion
    if (decoded.tokenVersion !== (user.tokenVersion || 0)) {
      return res.status(401).json({
        success: false,
        message: 'Session invalidated due to password rotation or administrative session revocation. Please login again.',
      });
    }

    // 5. Check if password was changed after token issuance
    if (user.passwordChangedAt) {
      const changedTimestamp = Math.floor(user.passwordChangedAt.getTime() / 1000);
      if (decoded.iat && decoded.iat < changedTimestamp - 1) {
        return res.status(401).json({
          success: false,
          message: 'Password was updated after this session was created. Please login again.',
        });
      }
    }

    // 6. Check account status (Suspended users cannot use previously issued tokens)
    if (user.status === 'Suspended') {
      return res.status(403).json({
        success: false,
        message: 'Your account is currently suspended. Please contact your organization administrator.',
      });
    }

    if (user.status === 'Deactivated') {
      return res.status(403).json({
        success: false,
        message: 'Your account has been deactivated. Access revoked.',
      });
    }

    // A missing or inactive role must never grant access, including Super Admin.
    if (!user.role || user.role.status !== 'Active') {
      return res.status(403).json({
        success: false,
        message: 'Access denied: Your assigned role is missing or inactive. Contact an administrator.',
      });
    }

    // A token is valid only while its device remains trusted. This also
    // invalidates existing sessions immediately when a device is revoked.
    const trustedDevice = await Device.findOne({
      userId: user._id,
      deviceIdHash: decoded.deviceIdHash,
      status: 'Trusted',
    }).select('_id deviceName trustScore lastRiskScore status');
    if (!trustedDevice) {
      return res.status(401).json({
        success: false,
        message: 'This device is no longer trusted. Complete sign-in again from an approved device.',
      });
    }

    // Attach verified user, current trusted device and token to request object
    req.user = user;
    req.device = trustedDevice;
    req.token = token;
    req.tokenExpiry = decoded.exp ? new Date(decoded.exp * 1000) : new Date(Date.now() + 7 * 86400 * 1000);
    next();
  } catch (error) {
    if (error.name === 'TokenExpiredError') {
      return res.status(401).json({
        success: false,
        message: 'Authorization token has expired. Please log in again.',
      });
    }
    if (error.name === 'JsonWebTokenError') {
      return res.status(401).json({
        success: false,
        message: 'Invalid authorization token. Signature verification failed.',
      });
    }

    console.error('[AuthMiddleware Error]:', error.message);
    return res.status(401).json({
      success: false,
      message: 'Not authorized: Authentication failed.',
    });
  }
};

// Permission-based authorization middleware
export const requirePermission = (permissionCode) => {
  return (req, res, next) => {
    if (!req.user || !req.user.role) {
      return res.status(403).json({
        success: false,
        message: 'Access denied: No role assigned to your account.',
      });
    }

    // Never allow an inactive role to bypass authorization, including Super Admin.
    if (req.user.role.status !== 'Active') {
      return res.status(403).json({
        success: false,
        message: 'Access denied: Your assigned role is currently inactive.',
      });
    }

    // Super Admin has full unrestricted access only while the role is active.
    if (req.user.role.name === 'Super Admin') {
      return next();
    }

    const userPermissions = req.user.role.permissions || [];
    const hasPermission = userPermissions.some(
      (perm) => (typeof perm === 'string' ? perm === permissionCode : perm.code === permissionCode)
    );

    if (!hasPermission) {
      return res.status(403).json({
        success: false,
        message: `Forbidden: You do not possess the required permission [${permissionCode}] to perform this action.`,
      });
    }

    next();
  };
};

// Role-based authorization middleware (for routes restricted to specific roles)
export const requireRole = (...allowedRoles) => {
  return (req, res, next) => {
    if (!req.user || !req.user.role) {
      return res.status(403).json({
        success: false,
        message: 'Access denied: No role assigned to your account.',
      });
    }

    if (req.user.role.status !== 'Active') {
      return res.status(403).json({
        success: false,
        message: 'Access denied: Your assigned role is currently inactive.',
      });
    }

    if (req.user.role.name === 'Super Admin') {
      return next();
    }

    if (!allowedRoles.includes(req.user.role.name)) {
      return res.status(403).json({
        success: false,
        message: `Access forbidden: Requires one of following roles: ${allowedRoles.join(', ')}`,
      });
    }

    next();
  };
};


// Authorization helper for routes that accept one of several capabilities.
export const requireAnyPermission = (...permissionCodes) => {
  return (req, res, next) => {
    if (!req.user?.role || req.user.role.status !== 'Active') {
      return res.status(403).json({
        success: false,
        message: 'Access denied: No active role is assigned to your account.',
      });
    }

    if (req.user.role.name === 'Super Admin') return next();

    const granted = new Set(
      (req.user.role.permissions || []).map((permission) =>
        typeof permission === 'string' ? permission : permission?.code
      )
    );

    if (permissionCodes.some((code) => granted.has(code))) return next();

    return res.status(403).json({
      success: false,
      message: `Forbidden: Requires one of these permissions: ${permissionCodes.join(', ')}.`,
    });
  };
};
